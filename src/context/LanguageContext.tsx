const normalizeLanguageTag = (tag: string): string => tag.trim().replace('_', '-');

const detectDeviceLanguage = (): Language => {
  const locales = RNLocalize.getLocales();
  const primary = locales?.[0];
  const languageTag = primary?.languageTag ? normalizeLanguageTag(primary.languageTag) : '';
  const languageCode = primary?.languageCode ?? '';
  const countryCode = primary?.countryCode ?? '';

  const tagLower = languageTag.toLowerCase();

  if (tagLower === 'pt-br' || (languageCode === 'pt' && countryCode === 'BR')) return 'pt-BR';
  if (tagLower === 'es-mx' || (languageCode === 'es' && countryCode === 'MX')) return 'es-MX';

  if (languageCode === 'zh') return 'zh';

  const exact = supportedLanguages.find(l => l.toLowerCase() === tagLower);
  if (exact) return exact;

  const byLanguageCode = supportedLanguages.find(l => l.toLowerCase() === languageCode.toLowerCase());
  if (byLanguageCode) return byLanguageCode;

  return 'en';
};

